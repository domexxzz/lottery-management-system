import type { Role } from "@prisma/client";

/**
 * ใครคุยกับใครได้
 *
 * กฎเดียวที่ระบบนี้ต้องการ: Agent คุยกันเองไม่ได้ คุยได้เฉพาะกับ Owner หรือ Admin
 * ส่วน Owner กับ Admin คุยได้กับทุกคน
 *
 * เหตุผลไม่ใช่เรื่องเทคนิค แต่เป็นเรื่องการกำกับ ตัวแทนแต่ละรายเห็นข้อมูล
 * เฉพาะบิลของตัวเองอยู่แล้วตามกฎขอบเขต ถ้าเปิดให้คุยกันเองได้ ข้อมูลยอดและ
 * ราคาจะไหลข้ามตัวแทนผ่านช่องทางที่ระบบมองไม่เห็นและตรวจสอบย้อนหลังไม่ได้
 *
 * แยกเป็นโมดูลบริสุทธิ์ ไม่พึ่งฐานข้อมูล เพื่อให้ทดสอบกฎได้ตรง ๆ
 * เหมือนที่ auth/scope.ts ทำกับกฎขอบเขตข้อมูล
 */

/** บทบาทที่คุยได้กับทุกคนในองค์กร */
const STAFF_ROLES: readonly Role[] = ["OWNER", "ADMIN"];

export function isStaff(role: Role): boolean {
  return STAFF_ROLES.includes(role);
}

/**
 * คู่สนทนานี้คุยกันได้หรือไม่
 *
 * ไม่สนใจลำดับ คุยได้ต้องคุยได้ทั้งสองทาง ไม่มีกรณีที่ฝั่งหนึ่งทักได้
 * แต่อีกฝั่งตอบไม่ได้ เพราะจะกลายเป็นห้องที่ค้างอยู่ครึ่งเดียว
 */
export function canConverse(a: Role, b: Role): boolean {
  return isStaff(a) || isStaff(b);
}

/** ข้อความอธิบายเมื่อคุยไม่ได้ ใช้ทั้งใน API และหน้าจอ */
